export interface Crop {
  name: string;
  icon: string;
  plantingSeason: string;
  harvestSeason: string;
  rainfall: string;
  irrigationNeeded: boolean;
  regions: string[];
  tips: string;
  yieldPerHectare: string;
  soilType: string;
  temperatureRange: string;
}

export interface CropCategory {
  id: string;
  name: string;
  icon: string;
  description: string;
  crops: Crop[];
}

export interface Season {
  name: string;
  type: "rainy" | "dry" | "harmattan";
  months: number[];
}

export interface LivestockAnimal {
  name: string;
  icon: string;
  bestSeason: string;
  breedingSeason: string;
  housing: string;
  feeding: string;
  regions: string[];
  tips: string;
  diseases?: { name: string; signs: string; prevention: string }[];
  breeds?: string[];
}

export interface LivestockCategory {
  id: string;
  name: string;
  icon: string;
  description: string;
  animals: LivestockAnimal[];
}

